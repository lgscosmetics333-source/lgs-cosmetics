import dotenv from "dotenv";
import { fileURLToPath } from "node:url";
import { randomBytes } from "node:crypto";
import fs from "node:fs";
import { ekart, ekartReadiness } from "../services/ekartClient.js";

const envPath = fileURLToPath(new URL("../.env", import.meta.url));
dotenv.config({ path: envPath, quiet: true, override: true });
const flag = process.argv[2] || "--status";
function setLocalValues(values) {
  let content = fs.existsSync(envPath) ? fs.readFileSync(envPath, "utf8") : "";
  for (const [name, value] of Object.entries(values)) {
    const line = `${name}=${JSON.stringify(String(value))}`;
    const pattern = new RegExp(`^${name}=.*$`, "m");
    content = pattern.test(content) ? content.replace(pattern, () => line) : `${content.trimEnd()}\n${line}\n`;
    process.env[name] = String(value);
  }
  fs.writeFileSync(envPath, content);
}
try {
  if (flag === "--init-local") {
    const defaults = { EKART_ENABLED: "false", EKART_BASE_URL: "https://app.elite.ekartlogistics.in", EKART_RATE_MODE: "fixed", EKART_SERVICE: "SURFACE",
      EKART_PICKUP_PINCODE: "", EKART_PICKUP_ALIAS: "", EKART_RETURN_ALIAS: "", EKART_SELLER_NAME: "LGS Cosmetics", EKART_SELLER_ADDRESS: "", EKART_SELLER_GSTIN: "", EKART_PACKAGING_WEIGHT_GRAMS: "0", EKART_BOX_PADDING_CM: "0" };
    setLocalValues({ ...Object.fromEntries(Object.entries(defaults).filter(([key]) => process.env[key] === undefined)),
      ...(!process.env.EKART_QUOTE_SECRET ? { EKART_QUOTE_SECRET: randomBytes(32).toString("hex") } : {}),
      ...(!process.env.EKART_WEBHOOK_SECRET ? { EKART_WEBHOOK_SECRET: randomBytes(15).toString("hex") } : {}),
    });
    console.log("Local Ekart settings initialized. Existing credentials preserved; secrets hidden.");
  } else if (flag === "--check-connection") {
    await ekart.accessToken(); console.log("PASS: Ekart API authentication succeeded. Token hidden. No shipment created.");
  } else if (flag === "--addresses") {
    const addresses = await ekart.request("/api/v2/addresses");
    if (!Array.isArray(addresses)) throw new Error("Unexpected Ekart address response.");
    console.log(JSON.stringify(addresses.map(a => ({ alias: a.alias, pincode: a.pincode })), null, 2));
  } else if (flag === "--register-webhook") {
    const base = new URL(process.env.EKART_PUBLIC_BACKEND_URL || "");
    if (base.protocol !== "https:" || base.username || base.password || base.pathname !== "/" || base.search || base.hash) throw new Error("Set EKART_PUBLIC_BACKEND_URL to the public HTTPS backend origin.");
    const secret = process.env.EKART_WEBHOOK_SECRET;
    if (!secret || !/^[a-f0-9]{30}$/.test(secret)) throw new Error("Set EKART_WEBHOOK_SECRET to a random 30-character hex value (generated by --init-local).");
    const url = `${base.origin}/api/shipping/ekart/webhook/${secret}`;
    const current = await ekart.request("/api/v2/webhook");
    if (!Array.isArray(current)) throw new Error("Unexpected Ekart webhook list. Check it in the dashboard.");
    if (current.some(row => row.url === url && row.active && row.topics?.includes("track_updated"))) console.log("Tracking webhook already registered.");
    else {
      await ekart.request("/api/v2/webhook", { method: "POST", body: { url, secret, topics: ["track_updated"], active: true } });
      console.log("Tracking webhook registered. Secret URL hidden.");
    }
  } else if (flag !== "--status") throw new Error("Use --status, --init-local, --check-connection, --addresses or --register-webhook.");
  const status = ekartReadiness();
  console.log(JSON.stringify({ enabled: status.enabled, rateMode: status.rateMode, missing: status.missing }));
} catch (error) {
  console.error(error.message); process.exitCode = 1;
}
